#!/usr/bin/env python3
"""Generate a production .env file with strong, unique secrets.

Produces the values the application *can* generate (SECRET_KEY, database and
Redis passwords) and leaves placeholders for the ones only you can supply
(domain names, object-storage keys, SMTP credentials).

    python deploy/generate-secrets.py > .env.production

Never commit the result. `.gitignore` already excludes `.env*` apart from the
examples, but check before you push.
"""

from __future__ import annotations

import argparse
import secrets
import string
import sys


def strong_password(length: int = 32) -> str:
    """A password safe to paste into a URL or a shell.

    Deliberately restricted to alphanumerics: the Redis password ends up
    inside a `redis://:pass@host` URL and the Postgres one inside a
    connection string, where `@`, `:`, `/` and `#` would need escaping and
    will eventually be got wrong by somebody.
    """
    alphabet = string.ascii_letters + string.digits
    return "".join(secrets.choice(alphabet) for _ in range(length))


TEMPLATE = """\
# Amora production configuration — GENERATED, DO NOT COMMIT.
#
# Generated by deploy/generate-secrets.py on {generated_at}.
# Secrets below are unique to this deployment. Rotating SECRET_KEY signs every
# user out; rotating the database password requires updating Postgres too.

# --- Fill these in yourself -------------------------------------------------
# The API's public hostname. Must already resolve to this server: Caddy
# requests a certificate for it on first boot.
API_DOMAIN=api.example.com
# Where Let's Encrypt sends expiry warnings.
ACME_EMAIL=you@example.com

# The frontend's public origin — the GitHub Pages URL, or your own domain.
FRONTEND_BASE_URL=https://{github_user}.github.io/amora
# Browser origins allowed to call the API. No trailing slash, comma separated.
# Note this is the ORIGIN only: https://user.github.io, not .../amora
CORS_ORIGINS=https://{github_user}.github.io

# --- Object storage (Cloudflare R2 shown; any S3-compatible service works) ---
# R2 dashboard -> R2 -> Manage API tokens -> Create (Object Read & Write).
# The endpoint is https://<account-id>.r2.cloudflarestorage.com
S3_ENDPOINT_URL=https://ACCOUNT_ID.r2.cloudflarestorage.com
S3_PUBLIC_ENDPOINT_URL=https://ACCOUNT_ID.r2.cloudflarestorage.com
S3_REGION=auto
S3_ACCESS_KEY=REPLACE_ME
S3_SECRET_KEY=REPLACE_ME
S3_BUCKET=amora-photos
S3_PRESIGN_TTL_SECONDS=900

# --- Email (Resend shown; any SMTP provider works) --------------------------
# Resend -> API Keys. The SMTP username is the literal string "resend".
SMTP_HOST=smtp.resend.com
SMTP_PORT=587
SMTP_USER=resend
SMTP_PASSWORD=REPLACE_ME
# Must be an address on a domain you have verified with the provider.
SMTP_FROM=no-reply@example.com

# --- Generated secrets ------------------------------------------------------
# Signs access tokens. Changing it invalidates every session immediately.
SECRET_KEY={secret_key}
POSTGRES_USER=amora
POSTGRES_PASSWORD={postgres_password}
POSTGRES_DB=amora
REDIS_PASSWORD={redis_password}

# --- Tuning -----------------------------------------------------------------
# Publishing the OpenAPI schema is useful during a soft launch, and is a map
# of the attack surface afterwards.
ENABLE_DOCS=false
REQUIRE_PHOTO_MODERATION=true
BCRYPT_ROUNDS=12
# Roughly (2 x CPU cores). Two workers fit comfortably in 768MB.
WEB_CONCURRENCY=2
BACKUP_RETENTION_DAYS=7
"""


def main() -> int:
    # Windows defaults stdout to cp1252 when redirected, which mangles the
    # non-ASCII characters in the comments and produces a file the app cannot
    # read. Force UTF-8 so `> .env.production` is byte-correct everywhere.
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--github-user",
        default="Prakhar924",
        help="GitHub username, used to prefill the Pages frontend URL",
    )
    parser.add_argument(
        "-o",
        "--output",
        help="Write to this path instead of stdout (avoids shell redirection "
        "encoding issues entirely)",
    )
    args = parser.parse_args()

    from datetime import UTC, datetime

    rendered = TEMPLATE.format(
        generated_at=datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC"),
        github_user=args.github_user,
        # 48 bytes of entropy, well past the 32-character minimum the app
        # enforces at boot.
        secret_key=secrets.token_urlsafe(48),
        postgres_password=strong_password(32),
        redis_password=strong_password(32),
    )
    if args.output:
        from pathlib import Path

        Path(args.output).write_text(rendered, encoding="utf-8")
        print(f"Wrote {args.output}", file=sys.stderr)
    else:
        sys.stdout.write(rendered)

    # Guidance goes to stderr so `> .env.production` captures only the config.
    print(
        "\nGenerated. Next:\n"
        "  1. Replace every REPLACE_ME and example.com value.\n"
        "  2. Keep this file out of git (.gitignore already covers .env*).\n"
        "  3. Verify with: python deploy/check-config.py .env.production\n",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
